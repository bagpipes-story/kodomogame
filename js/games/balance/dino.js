const PI = Math.PI;
const r2 = (v) => Math.round(v * 100) / 100;
const FY = 30; // 床（あしの 板の まんなか）。あしの そこは FY+0.5

// まがった ふとさの ある ぼう（くび・しっぽ・あし）: 点の 線に そって ふとさを かえた 形
function taper(list, ws) {
  const L = [];
  const R = [];
  for (let i = 0; i < list.length; i++) {
    const [x, y] = list[i];
    const [ax, ay] = list[Math.max(0, i - 1)];
    const [bx, by] = list[Math.min(list.length - 1, i + 1)];
    const len = Math.hypot(bx - ax, by - ay) || 1;
    const nx = -(by - ay) / len;
    const ny = (bx - ax) / len;
    L.push([r2(x + (nx * ws[i]) / 2), r2(y + (ny * ws[i]) / 2)]);
    R.push([r2(x - (nx * ws[i]) / 2), r2(y - (ny * ws[i]) / 2)]);
  }
  return [...L, ...R.reverse()];
}
// その ぼうを 凸の 四角に わけた 当たり判定（まがった ままだと 凸に ならないため）
function taperParts(list, ws) {
  const poly4 = taper(list, ws);
  const n = list.length;
  const parts = [];
  for (let i = 0; i < n - 1; i++) parts.push({ points: hull([poly4[i], poly4[i + 1], poly4[2 * n - 2 - i], poly4[2 * n - 1 - i]]) });
  return parts;
}

// なめらかな とじた形を いまの パスに たす（点と点の まんなかを とおる）
function addSmooth(ctx, list) {
  const n = list.length;
  const mid = (i) => [(list[i][0] + list[(i + 1) % n][0]) / 2, (list[i][1] + list[(i + 1) % n][1]) / 2];
  const m0 = mid(n - 1);
  ctx.moveTo(m0[0], m0[1]);
  for (let i = 0; i < n; i++) {
    const m = mid(i);
    ctx.quadraticCurveTo(list[i][0], list[i][1], m[0], m[1]);
  }
  ctx.closePath();
}
// いくつかの 形を 1つの からだに 見せる: 先に ぜんぶの ふちを 引いてから ぜんぶ ぬる（つなぎめの 線が きえる）
function silhouette(ctx, shapes, fill, stroke, w = 3) {
  ctx.lineJoin = 'round';
  for (const sh of shapes) {
    ctx.beginPath();
    addSmooth(ctx, sh);
    ctx.strokeStyle = stroke;
    ctx.lineWidth = w;
    ctx.stroke();
  }
  for (const sh of shapes) {
    ctx.beginPath();
    addSmooth(ctx, sh);
    ctx.fillStyle = fill;
    ctx.fill();
  }
}
// 形の 中だけに 描く（1つずつ きりぬく。もようは すけない 色で 描くので かさなっても かわらない）
function clipEach(ctx, shapes, fn) {
  for (const sh of shapes) {
    ctx.save();
    ctx.beginPath();
    addSmooth(ctx, sh);
    ctx.clip();
    fn();
    ctx.restore();
  }
}

// あし: にくしょく・とりあしの 足（ゆびは まえへ）と、ぞうの ような まるい 足
function theroFoot([bx, by], len) {
  return [[bx + 2.6, by - 1.6], [bx + 3.2, FY + 0.5], [bx - len, FY + 0.5], [bx - len - 1.2, FY - 0.6], [bx - len * 0.5, FY - 2.2], [bx - 1.8, by - 0.6]];
}
function columnFoot(x, w) {
  return [[x - w / 2 - 0.2, FY - 5], [x + w / 2 + 0.2, FY - 5], [x + w / 2 + 1.2, FY + 0.5], [x - w / 2 - 1.2, FY + 0.5]];
}
function legShapes(l) {
  const last = l.pts[l.pts.length - 1];
  return [taper(l.pts, l.ws), l.foot === 'thero' ? theroFoot(last, l.len ?? 8) : columnFoot(last[0], l.ws[l.ws.length - 1])];
}
function drawLeg(ctx, l, fill, stroke) {
  silhouette(ctx, legShapes(l), fill, stroke, 2.6);
  const [bx] = l.pts[l.pts.length - 1];
  if (l.foot === 'thero') { // つめ
    const tx = bx - (l.len ?? 8) - 1.2;
    poly(ctx, [[tx + 1.4, FY - 1.4], [tx - 1.2, FY + 0.2], [tx + 1.6, FY + 0.4]], stroke);
    if (l.sickle) poly(ctx, [[bx - 2, FY - 2.6], [bx - 4.6, FY - 7.4], [bx - 0.4, FY - 3.6]], '#e8e0d0'); // かぎづめ（ヴェロキラプトル など）
  } else {
    for (const dx of [-2, 0, 2]) dot(ctx, bx + dx - 1, FY - 0.4, 0.9, '#e8dcc4'); // ひづめの ような つめ
  }
}

// こまかい 絵の 道具
function teeth(ctx, [ax, ay], [bx, by], n, len, dir = 1, color = '#f6f2e6') {
  for (let i = 0; i < n; i++) {
    const t = (i + 0.5) / n;
    const x = ax + (bx - ax) * t;
    const y = ay + (by - ay) * t;
    poly(ctx, [[x - 0.6, y], [x, y + dir * len], [x + 0.6, y]], color);
  }
}
function scaleDots(ctx, x0, x1, y0, y1, n, color, r = 0.55) {
  for (let i = 0; i < n; i++) dot(ctx, x0 + ((i * 37) % 97) / 97 * (x1 - x0), y0 + ((i * 61) % 89) / 89 * (y1 - y0), r, color);
}
function featherEdge(ctx, list, len, color, w = 1) { // ふちに そって 外へ 毛の ような はね
  for (let i = 0; i < list.length - 1; i++) {
    const [ax, ay] = list[i];
    const [bx, by] = list[i + 1];
    const l = Math.hypot(bx - ax, by - ay) || 1;
    const nx = (by - ay) / l;
    const ny = -(bx - ax) / l;
    for (let t = 0; t < 1; t += 0.34) {
      const x = ax + (bx - ax) * t;
      const y = ay + (by - ay) * t;
      line(ctx, [[x, y], [x + nx * len + (bx - ax) / l * len * 0.5, y + ny * len + (by - ay) / l * len * 0.5]], color, w);
    }
  }
}
const amberEye = (ctx, x, y, r = 1.8, iris = '#e0a028') => colorEye(ctx, x, y, r, iris);

// ちいさい きょうりゅうは 全体を ちぢめる（線の 太さは ちぢめない）
function scaled(piece, k) {
  return {
    ...piece,
    inertiaScale: 1 / (k * k), // ちぢめて へった まわりにくさを おぎなう（kit.js の buildPieceBody）
    parts: piece.parts.map((p) => {
      const out = [];
      for (const q of p.points) { // ちぢめて ちかすぎる 点は まとめる（長さ0の辺で こわれるため）
        const v = { x: r2(q.x * k), y: r2(q.y * k) };
        const last = out[out.length - 1];
        if (!last || Math.hypot(v.x - last.x, v.y - last.y) > 0.6) out.push(v);
      }
      if (out.length > 3 && Math.hypot(out[0].x - out[out.length - 1].x, out[0].y - out[out.length - 1].y) <= 0.6) out.pop();
      return { ...p, points: out };
    }),
    draw(ctx) {
      ctx.save();
      ctx.scale(k, k);
      const thin = new Proxy(ctx, {
        get: (t, key) => {
          const v = t[key];
          return typeof v === 'function' ? v.bind(t) : v;
        },
        set: (t, key, v) => {
          t[key] = key === 'lineWidth' ? v / k : v;
          return true;
        },
      });
      piece.draw(thin, piece);
      ctx.restore();
    },
  };
}

// きょうりゅう 1ぴき: しっぽ・どう・くび・あたま（＋あご）を 1つの からだに、あしと うでを まえと うしろに わけて 描く
// legs/arms の near=true が てまえ（当たり判定にも 入れる）、false が むこうがわ（すこし くらい 色）
function dino(o) {
  const tail = taper(o.tail[0], o.tail[1]);
  const neck = taper(o.neck[0], o.neck[1]);
  const body = [tail, ...(o.tailExtra ?? []), o.torso, neck, ...(o.preHead ?? []), o.head, ...(o.jaw ? [o.jaw] : [])];
  const near = o.legs.filter((l) => l.near);
  const far = o.legs.filter((l) => !l.near);
  // あしの板は あしさきの はばから きめる（てで きめると ずれやすいため）
  let lo = Infinity;
  let hi = -Infinity;
  for (const l of o.legs) {
    const [bx] = l.pts[l.pts.length - 1];
    const w = l.ws[l.ws.length - 1];
    lo = Math.min(lo, l.foot === 'thero' ? bx - (l.len ?? 8) - 1.2 : bx - w / 2 - 1);
    hi = Math.max(hi, l.foot === 'thero' ? bx + 3 : bx + w / 2 + 1);
  }
  const board = o.board ?? [r2(hi - lo), r2((hi + lo) / 2)];
  return {
    color: o.color,
    line: o.line,
    pad: o.pad ?? 10,
    parts: [
      { points: blob(board[0], 4, 0.6, 0.6, { cx: board[1], cy: FY, seg: 2 }) },         // あしの板（絵は あしが かくす。かどは ほぼ しかく）
      { points: hull(o.torso) },
      { points: hull([...o.head, ...(o.jaw ?? [])]) },
      ...taperParts(o.neck[0], o.neck[1]),
      ...taperParts(o.tail[0], o.tail[1]),
      ...near.map((l) => ({ points: hull(taper(l.pts, l.ws)) })),
      ...(o.extraParts ?? []),
    ],
    draw(ctx) {
      for (const l of far) drawLeg(ctx, l, o.far, o.line);
      for (const a of o.arms ?? []) if (!a.near) silhouette(ctx, [taper(a.pts, a.ws)], o.far, o.line, 2.2);
      o.back?.(ctx);
      silhouette(ctx, body, o.color, o.line, 3);
      if (o.pattern) clipEach(ctx, body, () => o.pattern(ctx));
      for (const l of near) {
        drawLeg(ctx, l, o.legColor ?? o.color, o.line);
        o.legPattern?.(ctx, l);
      }
      for (const a of o.arms ?? []) {
        if (!a.near) continue;
        silhouette(ctx, [taper(a.pts, a.ws)], o.legColor ?? o.color, o.line, 2.2);
        const [hx, hy] = a.pts[a.pts.length - 1];
        for (const [dx, dy] of a.claws ?? [[-1.4, 1.6], [0.4, 2]]) poly(ctx, [[hx - 0.6, hy], [hx + dx, hy + dy], [hx + 0.6, hy + 0.2]], o.line); // て の つめ
      }
      o.details(ctx);
    },
  };
}

