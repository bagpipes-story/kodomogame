// うでの はね（ひじから 手くびに そって ながい はねを ならべる）
function wingFeathers(ctx, from, to, n, len, fill, stroke, tip) {
  for (let i = 0; i < n; i++) {
    const t = i / (n - 1);
    const x = from[0] + (to[0] - from[0]) * t;
    const y = from[1] + (to[1] - from[1]) * t;
    const ex = x + len[0] * (0.7 + t * 0.4);
    const ey = y + len[1] * (0.7 + t * 0.4);
    ctx.beginPath();
    ctx.moveTo(x - 1, y);
    ctx.quadraticCurveTo((x + ex) / 2 - 1.4, (y + ey) / 2 + 0.6, ex, ey);
    ctx.quadraticCurveTo((x + ex) / 2 + 1.4, (y + ey) / 2 - 0.6, x + 1, y);
    ctx.closePath();
    ctx.fillStyle = fill;
    ctx.fill();
    ctx.strokeStyle = stroke;
    ctx.lineWidth = 0.8;
    ctx.stroke();
    if (tip) dot(ctx, ex - len[0] * 0.08, ey - len[1] * 0.08, 0.7, tip);
  }
}

