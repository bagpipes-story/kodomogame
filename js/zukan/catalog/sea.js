// カニの あし（上から）: ふしを つないで、さきは とがった つめ。pts = つけね → ふしごとの 点（さいごが つめの さき）
function crabLeg(ctx, pts, w, tone, edge) {
  const n = pts.length;
  for (let i = 0; i < n - 2; i++) {
    const wa = w * (1 - i * 0.16);
    limb(ctx, pts[i], pts[i + 1], wa, wa * 0.86, tone[1], edge, 0.45);
    // ひらたい あしの 上の 面の 光
    stroke(ctx, [[pts[i][0], pts[i][1] - wa * 0.18], [pts[i + 1][0], pts[i + 1][1] - wa * 0.16]], 'rgba(255,236,200,0.3)', wa * 0.2, false);
  }
  const a = pts[n - 2];
  const b = pts[n - 1];
  const wd = w * (1 - (n - 2) * 0.16) * 0.8;
  const dx = b[0] - a[0];
  const dy = b[1] - a[1];
  const len = Math.hypot(dx, dy) || 1;
  shape(ctx, [[a[0] - (dy / len) * wd / 2, a[1] + (dx / len) * wd / 2], [b[0], b[1], 1], [a[0] + (dy / len) * wd / 2, a[1] - (dx / len) * wd / 2]], tone[2], edge, 0.4);
  for (let i = 1; i < n - 1; i++) disc(ctx, pts[i][0], pts[i][1], w * (1 - i * 0.16) * 0.42, tone[1], edge, 0.35);
}

