// v0.20.2: あたまが 小さく 口先が とがって サバの ように 見えたので、からだの 比率（あたまの 大きさ・ひれの 位置・おびれの 大きさ）を 直した
const TUNA_TOP = [[8, -20.6], [24, -16], [38, -10.6], [50, -6], [58, -3.6], [64, -2.4]];
