// からだの ふちに そった ひれ（せびれ〜おびれ〜しりびれが つながる）。i0 = せなかがわの はじまり、i1 = おなかがわの はじまり（0〜1）、h = 高さ
export function ribbonFin(B, i0, i1, h, flip = false) {
  const n = B.c.length;
  const top = flip ? B.down : B.up;
  const bottom = flip ? B.up : B.down;
  const off = (edgePts, i, k) => {
    const dx = edgePts[i][0] - B.c[i][0];
    const dy = edgePts[i][1] - B.c[i][1];
    const len = Math.hypot(dx, dy) || 1;
    return [edgePts[i][0] + (dx / len) * k, edgePts[i][1] + (dy / len) * k];
  };
  const a = Math.round(i0 * (n - 1));
  const b = Math.round(i1 * (n - 1));
  const pts = [];
  for (let i = a; i < n; i++) pts.push(off(top, i, Math.min(h, (i - a) * 0.6)));
  const tx = B.c[n - 1][0] - B.c[n - 3][0];
  const ty = B.c[n - 1][1] - B.c[n - 3][1];
  const tl = Math.hypot(tx, ty) || 1;
  pts.push([B.c[n - 1][0] + (tx / tl) * (h + 1.5), B.c[n - 1][1] + (ty / tl) * (h + 1.5)]);
  for (let i = n - 1; i >= b; i--) pts.push(off(bottom, i, Math.min(h, (i - b) * 0.6)));
  return pts;
}

