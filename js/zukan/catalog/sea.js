// 上下 対称の 形（上半分 y<=0 を 描いて、下へ うつす）。エイ・カメ・イカ など 上から 見た すがた 用
export function mirrorY(half) {
  const lower = half.slice(1, -1).reverse().map((p) => (p.length > 2 ? [p[0], -p[1], p[2]] : [p[0], -p[1]]));
  return half.concat(lower);
}

// 上下 両方に 描く（上がわ y<0 の つもりで 描く fn を、下にも うつす）
export function bothY(ctx, fn) {
  fn(1);
  ctx.save();
  ctx.scale(1, -1);
  fn(-1);
  ctx.restore();
}

// 形の 中に こまかい 点を ちらす（はだの つぶつぶ・ごまもよう）
export function sprinkle(ctx, pts, count, r, color, seed) {
  const rnd = seeded(seed);
  const [x0, y0, x1, y1] = bbox(pts);
  within(ctx, pts, () => {
    ctx.fillStyle = color;
    for (let i = 0; i < count; i++) {
      const x = x0 + rnd() * (x1 - x0);
      const y = y0 + rnd() * (y1 - y0);
      ctx.beginPath();
      ctx.arc(x, y, r * (0.6 + rnd() * 0.7), 0, PI * 2);
      ctx.fill();
    }
  });
}

// まるみ（v0.20.2）: 形の ふちへ むかって くらく、上を あかるく・下を くらく。なめらかな はだや 毛の ある 生きものの 立体感
export function volume(ctx, pts, { dark = 0.12, wide = 8, light = 0.14 } = {}) {
  const [x0, y0, x1, y1] = bbox(pts);
  within(ctx, pts, () => {
    // ふちの かげは 4だんに 分けて ぼかす（2だん だと 帯の さかいが りんかくの ように 見える）
    for (const k of [2, 1.5, 1, 0.5]) shape(ctx, pts, null, `rgba(0,0,0,${dark * 0.3})`, wide * k);
    ctx.fillStyle = vgrad(ctx, y0, y1, [`rgba(255,255,255,${light})`, 'rgba(255,255,255,0)', 'rgba(0,0,0,0)', `rgba(0,0,0,${dark})`]);
    ctx.fillRect(x0, y0, x1 - x0, y1 - y0);
  });
}

// みじかい 毛・すじ（むきの そろった 短い 線を ちらす）。angle = 毛の むき、spread = むきの ばらつき
export function fur(ctx, pts, count, len, angle, color, seed, spread = 0.6, width = 0.3) {
  const rnd = seeded(seed);
  const [x0, y0, x1, y1] = bbox(pts);
  within(ctx, pts, () => {
    ctx.strokeStyle = color;
    ctx.lineWidth = width;
    ctx.beginPath();
    for (let i = 0; i < count; i++) {
      const x = x0 + rnd() * (x1 - x0);
      const y = y0 + rnd() * (y1 - y0);
      const a = angle + (rnd() - 0.5) * spread;
      const l = len * (0.6 + rnd() * 0.8);
      ctx.moveTo(x, y);
      ctx.lineTo(x + Math.cos(a) * l, y + Math.sin(a) * l);
    }
    ctx.stroke();
  });
}

// 折れ線の 上で x に あたる y（ひれの つけねを からだの ふちに そわせる）
export function edgeY(line, x) {
  for (let i = 0; i < line.length - 1; i++) {
    const [x0, y0] = line[i];
    const [x1, y1] = line[i + 1];
    if ((x >= x0 && x <= x1) || (x <= x0 && x >= x1)) return y0 + ((y1 - y0) * (x - x0)) / (x1 - x0 || 1);
  }
  return line[line.length - 1][1];
}

// せなかが こく おなかが あかるい からだ（魚・クジラ・イルカ）。stops = 上から 下への 色。さいごに まるみの 光と かげ
export function shadedBody(ctx, pts, stops, edge, width = 0.6) {
  const [x0, y0, x1, y1] = bbox(pts);
  shape(ctx, pts, vgrad(ctx, y0, y1, stops), edge, width);
  within(ctx, pts, () => {
    ctx.fillStyle = vgrad(ctx, y0, y1, ['rgba(0,0,0,0.12)', 'rgba(255,255,255,0.2)', 'rgba(255,255,255,0)', 'rgba(255,255,255,0)', 'rgba(0,0,0,0.16)']);
    ctx.fillRect(x0, y0, x1 - x0, y1 - y0);
  });
}

// うろこ（v0.20.1）: 1まいずつ、うしろの ふちの かげ（こい 弧）と その 内がわの 光（あかるい 弧）を 描く。
// 前は うすい 弧だけで のっぺり 見えた。light = null で 光を 描かない
export function scales(ctx, pts, { size = 3, color = 'rgba(0,0,0,0.2)', light = 'rgba(255,255,255,0.28)', box = null, width = 0.4 } = {}) {
  const [x0, y0, x1, y1] = box ?? bbox(pts);
  const r = size * 0.56;
  const pass = (dx, rr, a, style, w) => {
    ctx.strokeStyle = style;
    ctx.lineWidth = w;
    ctx.beginPath();
    let row = 0;
    for (let y = y0; y <= y1; y += size * 0.78) {
      for (let x = x0 + (row % 2 ? size / 2 : 0); x <= x1; x += size) {
        ctx.moveTo(x + dx + rr * Math.cos(-a), y + rr * Math.sin(-a));
        ctx.arc(x + dx, y, rr, -a, a);
      }
      row++;
    }
    ctx.stroke();
  };
  within(ctx, pts, () => {
    if (light) pass(-size * 0.2, r * 0.9, 0.85, light, width * 1.5);
    pass(0, r, 1.15, color, width);
  });
}

// ひれ（v0.20.1）: 外形＋すじ（鰭条）。base = つけねの 線、tip = ふちの 線（同じ むきに ならべる）。
// spines = 前から 何本が とげか（太く 描く）、scallop = とげの あいだの まくの へこみ（0〜1。ふちが ぎざぎざに なる）、
// branch = やわらかい すじを さきで 2つに 分ける。つけねは からだの かげで こく、ふちへ むかって あかるく
export function fin(ctx, pts, tone, edge, { base = null, tip = null, n = 10, ray = 'rgba(0,0,0,0.28)', spines = 0, width = 0.5, margin = null, marginW = 1.2, scallop = 0, branch = false, shade = true } = {}) {
  let B = null;
  let T = null;
  let outline = pts;
  if (base) {
    B = resample(base, n);
    T = resample(tip, n);
  }
  if (scallop > 0 && B) {
    const top = [];
    for (let i = 0; i < n; i++) {
      top.push([T[i][0], T[i][1], 1]);
      if (i < n - 1) {
        const mx = (T[i][0] + T[i + 1][0]) / 2;
        const my = (T[i][1] + T[i + 1][1]) / 2;
        const bx = (B[i][0] + B[i + 1][0]) / 2;
        const by = (B[i][1] + B[i + 1][1]) / 2;
        top.push([mx + (bx - mx) * scallop, my + (by - my) * scallop]);
      }
    }
    outline = [...B, ...top.reverse()];
  }
  fill3d(ctx, outline, tone, edge, width, [0.3, 0.3]);
  within(ctx, outline, () => {
    if (shade && B) {
      const m = n >> 1;
      const h = Math.hypot(T[m][0] - B[m][0], T[m][1] - B[m][1]);
      stroke(ctx, B, 'rgba(0,0,0,0.2)', h * 0.5, false);
      stroke(ctx, T, 'rgba(255,255,255,0.2)', h * 0.36, false);
    }
    if (margin) shape(ctx, outline, null, margin, marginW * 2);
    if (!B) return;
    for (let i = 0; i < n; i++) {
      if (i < spines) {
        stroke(ctx, [B[i], T[i]], 'rgba(0,0,0,0.5)', 1, false);
        stroke(ctx, [B[i], T[i]], 'rgba(255,255,255,0.4)', 0.35, false);
      } else if (branch) {
        const mid = [B[i][0] + (T[i][0] - B[i][0]) * 0.55, B[i][1] + (T[i][1] - B[i][1]) * 0.55];
        stroke(ctx, [B[i], mid], ray, 0.42, false);
        for (const d of [-1, 1]) {
          const nb = T[Math.max(0, Math.min(n - 1, i + d))];
          stroke(ctx, [mid, [T[i][0] + (nb[0] - T[i][0]) * 0.28, T[i][1] + (nb[1] - T[i][1]) * 0.28]], ray, 0.3, false);
        }
      } else stroke(ctx, [B[i], T[i]], ray, 0.4, false);
    }
  });
}

// 目（v0.20.1）: 虹彩に まるみの かげ（上が こく 下が あかるい）、ひとみの まわりの ほそい 光の わ、ひとみ、光
export function eye(ctx, x, y, r, { iris = '#d8d2bc', pupil = '#0a0a0a', ring = 'rgba(0,0,0,0.6)', pupilR = 0.55 } = {}) {
  disc(ctx, x, y, r, iris, ring, 0.45);
  ctx.save();
  ctx.beginPath();
  ctx.arc(x, y, r, 0, PI * 2);
  ctx.clip();
  ctx.fillStyle = rgrad(ctx, x - r * 0.3, y + r * 0.5, r * 1.5, ['rgba(255,255,255,0.5)', 'rgba(255,255,255,0)', 'rgba(0,0,0,0.4)']);
  ctx.fillRect(x - r, y - r, r * 2, r * 2);
  ctx.restore();
  disc(ctx, x, y, r * pupilR + 0.3, 'rgba(255,236,170,0.55)');
  disc(ctx, x, y, r * pupilR, pupil);
  disc(ctx, x - r * 0.22, y - r * 0.24, r * 0.17, 'rgba(255,255,255,0.9)');
}

// ヘビの ような ながい からだ（ウナギ・ウツボ・チンアナゴ・タコの うで）。芯と 太さから りんかくを 作る。
// up = 進む むきの 左がわ（左→右へ のびる 芯なら 上）、down = 右がわ
export function snake(spine, widths, n = 48) {
  const c = resample(spine, n);
  const wAt = (t) => {
    const x = t * (widths.length - 1);
    const i = Math.min(widths.length - 2, Math.floor(x));
    return widths[i] + (widths[i + 1] - widths[i]) * (x - i);
  };
  const up = [];
  const down = [];
  for (let i = 0; i < n; i++) {
    const a = c[Math.max(0, i - 1)];
    const b = c[Math.min(n - 1, i + 1)];
    const len = Math.hypot(b[0] - a[0], b[1] - a[1]) || 1;
    const nx = (b[1] - a[1]) / len;
    const ny = -(b[0] - a[0]) / len;
    const w = wAt(i / (n - 1)) / 2;
    up.push([c[i][0] + nx * w, c[i][1] + ny * w]);
    down.push([c[i][0] - nx * w, c[i][1] - ny * w]);
  }
  // はしを まるく とじる
  const cap = (i, j, w) => {
    const len = Math.hypot(c[i][0] - c[j][0], c[i][1] - c[j][1]) || 1;
    return [c[i][0] + ((c[i][0] - c[j][0]) / len) * w, c[i][1] + ((c[i][1] - c[j][1]) / len) * w];
  };
  const head = cap(0, 1, wAt(0) * 0.45);
  const tail = cap(n - 1, n - 2, wAt(1) * 0.45);
  return { c, up, down, outline: [head, ...up, tail, ...down.slice().reverse()], wAt };
}

// さかな（真横・左むき。v0.20.1 で ぬりと 細部を 作りなおし）:
// うしろの ひれ → からだ（もよう → うろこ → まるみの かげ・てり）→ あたま（うろこの ない 面・えらぶた・あご・はなの あな）→ 手前の ひれ → 目
// F = { edge, body, stops, back[], front[], pattern(c)（うろこの 下の もよう）, scales, over(c)（うろこの 上の もよう）,
//       head（あたまの 形。うろこを 描かない）, headTone（あたまに かさねる 色）, gill（えらぶたの うしろの ふち）, preop（えらぶたの 前の 骨の 線）,
//       maxilla（上あごの 骨）, mouth, nostril, shine（わきばらの てりの 線）, lateral（側線）, eye, after(c) }
export function fish(ctx, F) {
  const edge = F.edge;
  for (const f of F.back ?? []) fin(ctx, f.pts, f.tone ?? F.finTone, edge, f);
  const [x0, y0, x1, y1] = bbox(F.body);
  shape(ctx, F.body, vgrad(ctx, y0, y1, F.stops), null);
  within(ctx, F.body, () => {
    F.pattern?.(ctx);
  });
  if (F.scales) scales(ctx, F.body, F.scales);
  within(ctx, F.body, () => {
    F.over?.(ctx);
    // まるみ: ふちへ むかって くらく（せなかと おなかの りんかく）、せなかの すこし 下に あかるい 帯
    shape(ctx, F.body, null, 'rgba(0,0,0,0.07)', 10);
    shape(ctx, F.body, null, 'rgba(0,0,0,0.1)', 4.4);
    ctx.fillStyle = vgrad(ctx, y0, y1, ['rgba(0,0,0,0.14)', 'rgba(255,255,255,0.2)', 'rgba(255,255,255,0)', 'rgba(255,255,255,0.08)', 'rgba(0,0,0,0.1)']);
    ctx.fillRect(x0, y0, x1 - x0, y1 - y0);
    if (F.shine) {
      stroke(ctx, F.shine, 'rgba(255,255,255,0.16)', (y1 - y0) * 0.1);
      stroke(ctx, F.shine, 'rgba(255,255,255,0.3)', (y1 - y0) * 0.028);
    }
    if (F.lateral) {
      stroke(ctx, F.lateral, F.lateralColor ?? 'rgba(0,0,0,0.3)', 0.5);
      stroke(ctx, F.lateral.map(([x, y]) => [x, y + 0.7]), 'rgba(255,255,255,0.22)', 0.4);
    }
    // あたま: うろこの ない なめらかな 面
    if (F.head) {
      shape(ctx, F.head, vgrad(ctx, y0, y1, F.stops), null);
      if (F.headTone) shape(ctx, F.head, F.headTone, null);
      const [hx0, hy0, hx1, hy1] = bbox(F.head);
      ctx.save();
      ctx.beginPath();
      trace(ctx, F.head, true);
      ctx.clip();
      ctx.fillStyle = rgrad(ctx, hx0 + (hx1 - hx0) * 0.45, hy0 + (hy1 - hy0) * 0.3, (hx1 - hx0) * 0.9, ['rgba(255,255,255,0.22)', 'rgba(255,255,255,0)', 'rgba(0,0,0,0.14)']);
      ctx.fillRect(hx0, hy0, hx1 - hx0, hy1 - hy0);
      F.headDetail?.(ctx);
      ctx.restore();
    }
    if (F.gill) {
      // えらぶた（うしろの ふちが もりあがり、その うしろに かげが おちる）
      stroke(ctx, F.gill.map(([x, y]) => [x + 1.5, y]), 'rgba(0,0,0,0.2)', 2.4);
      stroke(ctx, F.gill, 'rgba(0,0,0,0.5)', 0.65);
      stroke(ctx, F.gill.map(([x, y]) => [x - 0.9, y]), 'rgba(255,255,255,0.4)', 0.5);
    }
    if (F.preop) {
      stroke(ctx, F.preop, 'rgba(0,0,0,0.32)', 0.5);
      stroke(ctx, F.preop.map(([x, y]) => [x - 0.8, y]), 'rgba(255,255,255,0.28)', 0.4);
    }
  });
  shape(ctx, F.body, null, edge, 0.6);
  if (F.maxilla) {
    shape(ctx, F.maxilla, F.maxillaColor ?? 'rgba(255,255,255,0.3)', 'rgba(0,0,0,0.45)', 0.4);
  }
  if (F.mouth) stroke(ctx, F.mouth, 'rgba(0,0,0,0.65)', 0.6);
  if (F.nostril) {
    disc(ctx, F.nostril[0], F.nostril[1], 0.55, 'rgba(0,0,0,0.7)');
    disc(ctx, F.nostril[0] + 1.6, F.nostril[1] + 0.3, 0.4, 'rgba(0,0,0,0.55)');
  }
  for (const f of F.front ?? []) fin(ctx, f.pts, f.tone ?? F.finTone, edge, f);
  if (F.eye) eye(ctx, F.eye[0], F.eye[1], F.eye[2], F.eye[3]);
  F.after?.(ctx);
}

