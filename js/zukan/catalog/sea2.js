// サメ・エイの ひれ（すじの ない なめらかな ひれ）。spots = しろい 点の 数
function plainFin(ctx, pts, tone, edge, { spots = 0, spotColor = 'rgba(240,244,232,0.85)', seed = 1, spotR = 0.8, dark = 0.16 } = {}) {
  fill3d(ctx, pts, tone, edge, 0.5, [0.3, 0.3]);
  if (spots) sprinkle(ctx, pts, spots, spotR, spotColor, seed);
  volume(ctx, pts, { dark, wide: 2.6 });
  shape(ctx, pts, null, edge, 0.5);
}

// もりあがった すじ（下に かげ、上に 光）
function ridge(ctx, pts, dark = 'rgba(8,18,30,0.45)', light = 'rgba(210,226,238,0.4)') {
  stroke(ctx, pts.map(([x, y]) => [x, y + 0.7]), dark, 0.8);
  stroke(ctx, pts, light, 0.5);
}

