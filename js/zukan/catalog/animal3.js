// むこうがわの あし（blob(far, { all: true }) の 形）を こい 色で ぬり、うらがわ（右）に かげ
function farLegs(ctx, far, stops, edge, y0 = -10) {
  for (const lg of far) {
    shape(ctx, lg, vgrad(ctx, y0, 44, stops), edge, 0.5);
    within(ctx, lg, () => stroke(ctx, lg.map(([x, y]) => [x + 2.2, y]), 'rgba(30,26,22,0.2)', 3));
  }
}

// 手前の あしの うらがわの かげと 前がわの 光（関節の 列を ずらした 太い 線。ひじ・ひざより 下 だけ わたす）
function legShade(ctx, legs, dark = 'rgba(50,44,38,0.18)', light = 'rgba(255,255,255,0.28)') {
  for (const J of legs) {
    stroke(ctx, J.map(([x, y, r]) => [x + r * 0.75, y]), dark, 5);
    stroke(ctx, J.map(([x, y, r]) => [x + r * 0.95, y]), dark, 2);
    stroke(ctx, J.map(([x, y, r]) => [x - r * 0.45, y]), light, 1.6);
  }
}

// おなかの 下の かげ（はばは 絵 ぜんたい。はしを 作ると 四角い さかいめが 見える）。rgb = '60,54,48' など
function bellyShade(ctx, y0, y1, rgb, a = 0.2) {
  ctx.fillStyle = vgrad(ctx, y0, y1, [`rgba(${rgb},0)`, `rgba(${rgb},${a})`, `rgba(${rgb},0)`]);
  ctx.fillRect(-120, y0, 240, y1 - y0);
}

// まるい ふくらみの 光（かた・こし など）
function bulge(ctx, x, y, r, rgba = 'rgba(255,255,255,0.2)') {
  ctx.fillStyle = rgrad(ctx, x, y, r, [rgba, rgba.replace(/[\d.]+\)$/, '0)')]);
  ctx.fillRect(x - r, y - r, r * 2, r * 2);
}

// ひづめを、そこの まんなか (tx + hx) / 2 を ふくむ 形に 描く（blob の all の 形は ならびが 大きさ じゅんで、どれが どの あしか きまらない ため）
function hoofAt(ctx, shapes, tx, hx, h, color, opt) {
  const cx = (tx + hx) / 2;
  const s = shapes.find((p) => {
    const [x0, , x1, y1] = bbox(p);
    return cx >= x0 && cx <= x1 && y1 > 40;
  });
  if (s) hoof(ctx, s, tx, hx, h, color, opt);
}

