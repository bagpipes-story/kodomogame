const G = 44; // じめんの 高さ（立つ どうぶつの あしの うら）

// あしもとの うすい かげ（よこに ながい だえんは 点の 列で 描く。ctx.ellipse だと テストの はかりで たてにも 大きく 見られる）
function groundShadow(ctx, x0, x1, y = G) {
  shape(ctx, ell((x0 + x1) / 2, y + 0.6, (x1 - x0) / 2, 2.6, 28), 'rgba(70,58,44,0.14)');
}

// 点の 列の 一部（i0〜i1）だけを ふちの 線に する。つけねの ところは 線を 出さない
function openEdge(ctx, pts, i0, i1, color, w = 0.6) {
  stroke(ctx, pts.slice(i0, i1 + 1), color, w);
}

// 上が あかるく 下が くらい ぬり（stops は 上→下）
function baseFill(ctx, pts, stops) {
  const [, y0, , y1] = bbox(pts);
  shape(ctx, pts, vgrad(ctx, y0, y1, stops), null);
}

// ひづめ: そこ y、つま先 tx（左）・かかと hx（右）、高さ h（つま先がわ。かかとがわは ひくい）。
// split = 2つに わかれる ひづめ（前よりに わかれめの 線）。clip = あしの りんかく（はみださない ように）
function hoof(ctx, clip, tx, hx, h, color, { y = G, split = true, edge = 'rgba(20,14,10,0.8)' } = {}) {
  within(ctx, clip, () => {
    const poly = [[tx - 3, y + 2], [tx - 3, y - h], [tx + (hx - tx) * 0.45, y - h * 1.02], [hx + 3, y - h * 0.5], [hx + 3, y + 2]];
    shape(ctx, poly, lgrad(ctx, tx, y - h, hx, y, [color[0], color[1]]), null);
    stroke(ctx, [[tx - 1, y - h], [tx + (hx - tx) * 0.45, y - h * 1.02], [hx + 1, y - h * 0.5]], edge, 0.45);
    stroke(ctx, [[tx + (hx - tx) * 0.12, y - h * 0.9], [tx + (hx - tx) * 0.3, y - h * 0.5]], 'rgba(255,255,255,0.22)', 0.6);
    if (split) stroke(ctx, [[tx + (hx - tx) * 0.42, y - h * 0.96], [tx + (hx - tx) * 0.36, y]], edge, 0.5);
  });
}

// 毛なみの むき: どうは うしろ（右）へ すこし 下がり、おなかより 下（あし）は 下へ
const flowBody = (belly, a = 0.16) => (x, y) => (y > belly ? PI / 2 + (x < 0 ? 0.08 : -0.08) : a);


