// あしもとの うすい かげ
// （oval は テストの にせキャンバスで 大きな 円と して はかられるので、点の 列で 描く）
const ground = (ctx, cx, y, rx) => shape(ctx, ell(cx, y, rx, Math.max(1.6, rx * 0.07), 28), 'rgba(70,58,44,0.14)', null);

// しま・すじ（芯に そって 太さが かわる 帯）
function band(ctx, spine, widths, color, n = 14) {
  shape(ctx, snake(spine, widths, n).outline, color, null);
}

// ひげ（つけね (x, y) から のびる ほそい 線）。白い ひげは 白い 背景で 見えなく なるので、うすい はいいろの ふちを 下に しく
function whiskers(ctx, x, y, list, color = 'rgba(255,255,255,0.85)', w = 0.28) {
  const light = /rgba\(2[3-5]\d,/.test(color);
  for (const [dx, dy, bend = 0] of list) {
    const pts = [[x, y], [x + dx * 0.5, y + dy * 0.5 - bend], [x + dx, y + dy]];
    if (light) stroke(ctx, pts, 'rgba(110,92,76,0.45)', w + 0.3);
    stroke(ctx, pts, color, w);
  }
}

// 毛の からだの ぬり: 光の あたる グラデーション → もよう（pattern）→ 毛なみ（furs）→ まるみ（volume）→ ふち線
// 毛と もようは 形の 中だけ。ふち線は さいごに 1回（つなぎめに 線が 出ない）
function coat(ctx, outline, { stops, light = [0.3, 0.22], pattern = null, furs = [], vol = {}, edge = null, width = 0.6 }) {
  const [x0, y0, x1, y1] = bbox(outline);
  const w = x1 - x0;
  const h = y1 - y0;
  shape(ctx, outline, rgrad(ctx, x0 + w * light[0], y0 + h * light[1], Math.hypot(w, h) * 0.85, stops), null);
  if (pattern) within(ctx, outline, pattern);
  for (const f of furs) furFlow(ctx, outline, f.n, f.len, f.dir, f.color, f.seed, f.w ?? 0.3, f.spread ?? 0.35);
  volume(ctx, outline, vol);
  if (edge) shape(ctx, outline, null, edge, width);
}

// 毛の ふさで ぎざぎざに した りんかく（たてがみ・ほおの 毛・しっぽの 先）。pts を なめらかに つなぎ、外がわへ とがった ふさを ならべる
// n = ふさの 数、len = ふさの 長さ、side = 外がわの むき（1 = 進む むきの 左、-1 = 右）
function tufted(pts, n, len, side = 1, seed = 1, closed = true) {
  const P = resample(closed ? [...pts, pts[0]] : pts, n * 2 + 1);
  const rnd = seeded(seed);
  const out = [];
  for (let i = 0; i < P.length - (closed ? 1 : 0); i++) {
    const a = P[Math.max(0, i - 1)];
    const b = P[Math.min(P.length - 1, i + 1)];
    const l = Math.hypot(b[0] - a[0], b[1] - a[1]) || 1;
    const nx = ((b[1] - a[1]) / l) * side;
    const ny = (-(b[0] - a[0]) / l) * side;
    if (i % 2) {
      const k = len * (0.6 + rnd() * 0.8);
      const lean = (rnd() - 0.3) * 0.6;
      out.push([P[i][0] + nx * k + ((b[0] - a[0]) / l) * k * lean, P[i][1] + ny * k + ((b[1] - a[1]) / l) * k * lean, 1]);
    } else out.push([P[i][0], P[i][1]]);
  }
  return out;
}

// ゆらいだ しま（毛の もよう）。(x, y) から ang の むきへ len、太さ w。とちゅうで うねり、先が ほそく なる。
// soft = まわりに うすい ぼかしを つける（毛に なじむ）
function stripe(ctx, x, y, len, ang, w, color, seed, soft = 0.35) {
  const r = seeded(seed);
  const sp = [];
  const n = 5;
  const ph = r() * 6;
  const amp = 0.6 + r() * 1.2;
  for (let k = 0; k <= n; k++) {
    const t = k / n;
    const o = Math.sin(t * 3.2 + ph) * amp;
    sp.push([x + Math.cos(ang) * len * t - Math.sin(ang) * o, y + Math.sin(ang) * len * t + Math.cos(ang) * o]);
  }
  const ws = [w * 0.7, w, w * 0.95, w * 0.8, w * 0.5, w * 0.12];
  if (soft) {
    ctx.save();
    ctx.globalAlpha = soft;
    band(ctx, sp, ws.map((v) => v * 1.9 + 0.6), color);
    ctx.restore();
  }
  band(ctx, sp, ws, color);
}

// 毛の たば 1つ（たてがみ・ほおの 毛・ふさふさの しっぽ）。(x, y) から ang の むきへ len、とちゅうで bend だけ まがる。先が とがる。
// hi = たばの 片がわの 光の 色（null で なし）
function lock(ctx, x, y, ang, len, w, color, bend = 0.4, hi = null) {
  const sp = [[x, y]];
  let a = ang;
  let px = x;
  let py = y;
  for (const f of [0.36, 0.34, 0.3]) {
    px += Math.cos(a) * len * f;
    py += Math.sin(a) * len * f;
    sp.push([px, py]);
    a += bend / 2;
  }
  band(ctx, sp, [w, w * 0.92, w * 0.6, 0.12], color, 10);
  if (hi) stroke(ctx, sp.slice(0, 3).map(([qx, qy]) => [qx - Math.sin(ang) * w * 0.22, qy + Math.cos(ang) * w * 0.22]), hi, Math.max(0.3, w * 0.18));
}

// ふちの 毛（ふさふさした ふちを、ふちから 外へ はみ出す ほそい 毛で 描く）。E = ふちの 点の 列、
// dir(i, t) = その 場所の 毛の むき、col(t) = 色（t = 0〜1 の 場所）。1つの 色ごとに まとめて 描く
function fuzz(ctx, E, dir, col, n, len, seed, w = 0.45) {
  const r = seeded(seed);
  const groups = new Map();
  for (let k = 0; k < n; k++) {
    const t = r();
    const f = t * (E.length - 1);
    const i = Math.min(E.length - 2, Math.floor(f));
    const u = f - i;
    const x = E[i][0] + (E[i + 1][0] - E[i][0]) * u;
    const y = E[i][1] + (E[i + 1][1] - E[i][1]) * u;
    const a = dir(i, t) + (r() - 0.5) * 0.5;
    const l = len * (0.5 + r() * 0.8);
    const c = col(t);
    if (!groups.has(c)) groups.set(c, []);
    groups.get(c).push([x - Math.cos(a) * l * 0.4, y - Math.sin(a) * l * 0.4, x + Math.cos(a) * l * 0.6, y + Math.sin(a) * l * 0.6, a + (r() - 0.5) * 0.6]);
  }
  ctx.lineCap = 'round';
  ctx.lineWidth = w;
  for (const [c, list] of groups) {
    ctx.strokeStyle = c;
    ctx.beginPath();
    for (const [x0, y0, x1, y1, a2] of list) {
      ctx.moveTo(x0, y0);
      ctx.lineTo((x0 + x1) / 2, (y0 + y1) / 2);
      ctx.lineTo(x1 + Math.cos(a2) * 0.6, y1 + Math.sin(a2) * 0.6);
    }
    ctx.stroke();
  }
}

// ---------- あし（blob の 関節の 列）の 部品 ----------

// あしの うらがわ（右）の かげと 前がわの 光。J = 関節の 列 [[x, y, r], …]（ひじ・ひざより 下 だけ わたす。上まで ひくと どうに すじが 出る）
function legShade(ctx, J, dark = 'rgba(60,40,24,0.18)', lightC = 'rgba(255,240,220,0.16)') {
  stroke(ctx, J.map(([x, y, r]) => [x + r * 0.7, y]), dark, 4.6);
  stroke(ctx, J.map(([x, y, r]) => [x + r * 0.95, y]), dark, 1.8);
  stroke(ctx, J.map(([x, y, r]) => [x - r * 0.45, y]), lightC, 1.4);
}

// 関節の 列の とちゅう（ts = 0〜1 の 場所）に、あしを よこぎる 帯（しま・くつしたの さかい）を 描く
function legBands(ctx, J, ts, color, w = 2) {
  const L = [0];
  for (let i = 1; i < J.length; i++) L.push(L[i - 1] + Math.hypot(J[i][0] - J[i - 1][0], J[i][1] - J[i - 1][1]));
  for (const t of ts) {
    const d = t * L[L.length - 1];
    let i = 1;
    while (i < J.length - 1 && L[i] < d) i++;
    const u = (d - L[i - 1]) / (L[i] - L[i - 1] || 1);
    const x = J[i - 1][0] + (J[i][0] - J[i - 1][0]) * u;
    const y = J[i - 1][1] + (J[i][1] - J[i - 1][1]) * u;
    const r = J[i - 1][2] + (J[i][2] - J[i - 1][2]) * u;
    const a = Math.atan2(J[i][1] - J[i - 1][1], J[i][0] - J[i - 1][0]) + PI / 2;
    band(ctx, [[x - Math.cos(a) * r * 1.3, y - Math.sin(a) * r * 1.3 - 0.4], [x, y], [x + Math.cos(a) * r * 1.3, y + Math.sin(a) * r * 1.3 + 0.6]], [w * 0.5, w, w * 0.5], color);
  }
}

// むこうがわの あし（blob の all: true で 作った 形の 列）を こい 色で 描く
function farLegs(ctx, legs, stops, edge, y0 = -10, y1 = 40) {
  for (const lg of legs) {
    shape(ctx, lg, vgrad(ctx, y0, y1, stops), null);
    within(ctx, lg, () => stroke(ctx, lg.map(([x, y]) => [x + 2.4, y]), 'rgba(30,18,10,0.2)', 3.4));
    shape(ctx, lg, null, edge, 0.5);
  }
}

// りんかく（blob の 点の 列）の 上の ふち・下の ふちを x の じゅんに とり出す（ふちの 毛 fuzz に わたす）。
// 下の ふちは yMax より 上の 点だけ（あしの ふちを ひろわない ため）
function edgeOf(outline0, x0, x1, n, top = true, yMax = Infinity) {
  // blob の りんかくは まっすぐな ところの 点が すくない（間引いて ある）ので、まず 0.8 ごとに 点を おぎなう
  const outline = [];
  for (let i = 0; i < outline0.length; i++) {
    const a = outline0[i];
    const b = outline0[(i + 1) % outline0.length];
    const m = Math.max(1, Math.ceil(Math.hypot(b[0] - a[0], b[1] - a[1]) / 0.8));
    for (let k = 0; k < m; k++) outline.push([a[0] + ((b[0] - a[0]) * k) / m, a[1] + ((b[1] - a[1]) * k) / m]);
  }
  const out = [];
  for (let i = 0; i <= n; i++) {
    const x = x0 + ((x1 - x0) * i) / n;
    let best = null;
    for (const [px, py] of outline) {
      if (Math.abs(px - x) > 1.2 || py > yMax) continue;
      if (best === null || (top ? py < best : py > best)) best = py;
    }
    // となりの 点から 大きく とぶ 点は すてる（あしの つけねで 反対がわの ふちを ひろうと、毛が たての すじに なる）
    if (best !== null && (!out.length || Math.abs(best - out[out.length - 1][1]) < 5)) out.push([x, best]);
  }
  return out;
}

