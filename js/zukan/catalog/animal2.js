// あしもとの うすい かげ
// （oval は テストの にせキャンバスで 大きな 円と して はかられるので、点の 列で 描く）
const ground = (ctx, cx, y, rx) => shape(ctx, ell(cx, y, rx, Math.max(1.6, rx * 0.07), 28), 'rgba(70,58,44,0.14)', null);

// しま・すじ（芯に そって 太さが かわる 帯）
function band(ctx, spine, widths, color, n = 14) {
  shape(ctx, snake(spine, widths, n).outline, color, null);
}

// ひげ（つけね (x, y) から のびる ほそい 線）
function whiskers(ctx, x, y, list, color = 'rgba(255,255,255,0.85)', w = 0.28) {
  for (const [dx, dy, bend = 0] of list) stroke(ctx, [[x, y], [x + dx * 0.5, y + dy * 0.5 - bend], [x + dx, y + dy]], color, w);
}

// 毛の からだの ぬり: 光の あたる グラデーション → もよう（pattern）→ 毛なみ（furs）→ まるみ（volume）→ ふち線
// 毛と もようは 形の 中だけ。ふち線は さいごに 1回（つなぎめに 線が 出ない）
function coat(ctx, outline, { stops, light = [0.3, 0.22], pattern = null, furs = [], vol = {}, edge = null, width = 0.6 }) {
  const [x0, y0, x1, y1] = bbox(outline);
  const w = x1 - x0;
  const h = y1 - y0;
  shape(ctx, outline, rgrad(ctx, x0 + w * light[0], y0 + h * light[1], Math.hypot(w, h) * 0.85, stops), null);
  if (pattern) within(ctx, outline, pattern);
  for (const f of furs) furFlow(ctx, outline, f.n, f.len, f.dir, f.color, f.seed, f.w ?? 0.3, f.spread ?? 0.35);
  volume(ctx, outline, vol);
  if (edge) shape(ctx, outline, null, edge, width);
}

// 毛の ふさで ぎざぎざに した りんかく（たてがみ・ほおの 毛・しっぽの 先）。pts を なめらかに つなぎ、外がわへ とがった ふさを ならべる
// n = ふさの 数、len = ふさの 長さ、side = 外がわの むき（1 = 進む むきの 左、-1 = 右）
function tufted(pts, n, len, side = 1, seed = 1, closed = true) {
  const P = resample(closed ? [...pts, pts[0]] : pts, n * 2 + 1);
  const rnd = seeded(seed);
  const out = [];
  for (let i = 0; i < P.length - (closed ? 1 : 0); i++) {
    const a = P[Math.max(0, i - 1)];
    const b = P[Math.min(P.length - 1, i + 1)];
    const l = Math.hypot(b[0] - a[0], b[1] - a[1]) || 1;
    const nx = ((b[1] - a[1]) / l) * side;
    const ny = (-(b[0] - a[0]) / l) * side;
    if (i % 2) {
      const k = len * (0.6 + rnd() * 0.8);
      const lean = (rnd() - 0.3) * 0.6;
      out.push([P[i][0] + nx * k + ((b[0] - a[0]) / l) * k * lean, P[i][1] + ny * k + ((b[1] - a[1]) / l) * k * lean, 1]);
    } else out.push([P[i][0], P[i][1]]);
  }
  return out;
}

