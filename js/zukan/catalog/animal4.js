// とじた りんかくを なめらかに 点 n こに ならべなおす
function loop(pts, n) {
  return resample([...pts, pts[0]], n + 1).slice(0, n);
}

// とじた 形の まわる むき（画面で 時計まわりなら 1）
function turn(pts) {
  let a = 0;
  for (let i = 0; i < pts.length; i++) {
    const p = pts[i];
    const q = pts[(i + 1) % pts.length];
    a += p[0] * q[1] - q[0] * p[1];
  }
  return a > 0 ? 1 : -1;
}

// ゆるい でこぼこの ふち: りんかくを 点 n こに して、外がわへ ゆるく 波うたせる（毛の かたまり）。
// keep(x, y) が true の ところは ずらさない（毛の みじかい ところ）
function hairy(pts, n, amp, seed, keep = null) {
  const p = loop(pts, n);
  const r = seeded(seed);
  const s = turn(p);
  const ph = r() * 6;
  return p.map((q, i) => {
    if (keep && keep(q[0], q[1])) return q;
    const a = p[(i - 1 + n) % n];
    const b = p[(i + 1) % n];
    const dx = b[0] - a[0];
    const dy = b[1] - a[1];
    const l = Math.hypot(dx, dy) || 1;
    const k = amp * (0.65 * Math.sin(i * 0.7 + ph) + 0.35 * Math.sin(i * 1.9 + ph * 2) + (r() - 0.5) * 0.5);
    return [q[0] + (s * dy / l) * k, q[1] - (s * dx / l) * k];
  });
}

// ふちの 毛: りんかくに そって、内がわから 外へ はみ出す 短い 毛を ならべる（ふちの 線を やわらかく かくす）。
// tilt = 外むきから どれだけ かたむけるか（毛なみの むき）。keep(x, y) が true の ところには 描かない
function fringe(ctx, pts, n, len, color, seed, { width = 0.45, tilt = 0.6, keep = null } = {}) {
  const p = loop(pts, n);
  const r = seeded(seed);
  const s = turn(p);
  ctx.beginPath();
  for (let i = 0; i < n; i++) {
    const q = p[i];
    if (keep && keep(q[0], q[1])) continue;
    const a = p[(i - 1 + n) % n];
    const b = p[(i + 1) % n];
    const dx = b[0] - a[0];
    const dy = b[1] - a[1];
    const l = Math.hypot(dx, dy) || 1;
    const nx = (s * dy) / l;
    const ny = (-s * dx) / l;
    const ang = Math.atan2(ny, nx) + tilt + (r() - 0.5) * 0.5;
    const L = len * (0.5 + r() * 0.8);
    const sx = q[0] - nx * L * 0.45;
    const sy = q[1] - ny * L * 0.45;
    ctx.moveTo(sx, sy);
    ctx.lineTo(sx + Math.cos(ang) * L * 0.55, sy + Math.sin(ang) * L * 0.55);
    ctx.lineTo(sx + Math.cos(ang + 0.3) * L, sy + Math.sin(ang + 0.3) * L);
  }
  ctx.strokeStyle = color;
  ctx.lineWidth = width;
  ctx.lineCap = 'round';
  ctx.stroke();
}

// 点が 形の 中に あるか（とげの つけねを えらぶ ため）
function inside(pts, x, y) {
  let c = false;
  for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
    const [xi, yi] = pts[i];
    const [xj, yj] = pts[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
}

// 芯（点の 列）に そった 毛の むき。芯から はなれた 毛は すこし 外へ ひらく
function along(spine, splay = 0.45) {
  return (x, y) => {
    let best = 0;
    let bd = Infinity;
    for (let i = 0; i < spine.length; i++) {
      const d = (spine[i][0] - x) ** 2 + (spine[i][1] - y) ** 2;
      if (d < bd) { bd = d; best = i; }
    }
    const a = spine[Math.max(0, best - 1)];
    const b = spine[Math.min(spine.length - 1, best + 1)];
    const ang = Math.atan2(b[1] - a[1], b[0] - a[0]);
    const side = (b[0] - a[0]) * (y - spine[best][1]) - (b[1] - a[1]) * (x - spine[best][0]);
    return ang + (side > 0 ? splay : -splay) * Math.min(1, Math.sqrt(bd) / 12);
  };
}

