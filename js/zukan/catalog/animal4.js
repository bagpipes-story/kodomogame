// はねの かさなり: 形の 中に、うろこの ような 小さな 弧を ならべる（cols × rows。むきは うしろへ）
function featherRows(ctx, pts, x0, y0, x1, y1, step, color, seed, w = 0.4) {
  const r = seeded(seed);
  within(ctx, pts, () => {
    ctx.beginPath();
    for (let y = y0; y < y1; y += step * 0.8) {
      const off = (Math.round((y - y0) / (step * 0.8)) % 2) * step * 0.5;
      for (let x = x0 + off; x < x1; x += step) {
        const jx = x + (r() - 0.5) * step * 0.3;
        const jy = y + (r() - 0.5) * step * 0.2;
        ctx.moveTo(jx - step * 0.1, jy - step * 0.45);
        ctx.bezierCurveTo(jx + step * 0.35, jy - step * 0.35, jx + step * 0.35, jy + step * 0.35, jx - step * 0.1, jy + step * 0.45);
      }
    }
    ctx.strokeStyle = color;
    ctx.lineWidth = w;
    ctx.stroke();
  });
}

// 1まいの 長い はね（じく と はねの ふち）。spine = じくの 点の 列、widths = はばの 列
function plume(ctx, spine, widths, fill, edge, shaft, n = 30) {
  const F = snake(spine, widths, n);
  shape(ctx, F.outline, fill, edge, 0.4);
  stroke(ctx, F.c.slice(0, n - 2), shaft, 0.45);
  return F;
}

// うろこの ある あし（a → b、太さ wa → wb）。よこの すじで うろこ
function scaledLeg(ctx, a, b, wa, wb, fill, edge, rings = 8) {
  limb(ctx, a, b, wa, wb, fill, edge, 0.45);
  const dx = b[0] - a[0];
  const dy = b[1] - a[1];
  const l = Math.hypot(dx, dy) || 1;
  const nx = -dy / l;
  const ny = dx / l;
  for (let k = 1; k < rings; k++) {
    const t = k / rings;
    const w = (wa + (wb - wa) * t) * 0.48;
    const cx = a[0] + dx * t;
    const cy = a[1] + dy * t;
    stroke(ctx, [[cx - nx * w, cy - ny * w], [cx + dx / l * 0.6, cy + dy / l * 0.6], [cx + nx * w, cy + ny * w]], 'rgba(90,50,20,0.35)', 0.35);
  }
  stroke(ctx, [[a[0] - nx * wa * 0.2, a[1] - ny * wa * 0.2], [b[0] - nx * wb * 0.2, b[1] - ny * wb * 0.2]], 'rgba(255,255,255,0.3)', Math.max(0.6, wb * 0.25), false);
}

